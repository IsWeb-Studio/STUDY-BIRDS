// ─── Helpers ──────────────────────────────────────────────────────────────────
Country? countryByIso2(String iso2) {
  try {
    return kCountries.firstWhere((c) => c.iso2 == iso2.toUpperCase());
  } catch (_) {
    return null;
  }
}

/// Parse "+966501234567" → (country, localDigits). Returns null if not parseable.
({Country country, String local})? parseFullPhone(String full) {
  if (!full.startsWith('+')) return null;
  final digits = full.substring(1);
  for (final len in [3, 2, 1]) {
    if (digits.length <= len) continue;
    final code = digits.substring(0, len);
    try {
      final c = kCountries.firstWhere((c) => c.dialCode == code);
      return (country: c, local: digits.substring(len));
    } catch (_) {}
  }
  return null;
}

